def mostrar_palabra(palabra, letras_adivinadas):
    palabra_mostrada = ""
    for letra in palabra:
        if letra in letras_adivinadas:
            palabra_mostrada += letra + " "
        else:
            palabra_mostrada += "_ "
    print(palabra_mostrada.strip())



def juego():
    palabra = random.choice(PALABRAS_AHORCADO)
    palabra = palabra.upper()
    letras_adivinadas = []
    letras_falladas = []
    intentos = 6
    print("¡Bienvenido al juego del ahorcado!")
    print("Tienes", intentos, "intentos para adivinar la palabra.")
    while intentos > 0:
        mostrar_palabra(palabra, letras_adivinadas)
        letra = input("Ingresa una letra: ").upper()
        if letra in letras_adivinadas:
            print("Ya has adivinado esa letra. Intenta con otra.")
            continue
        if letra in palabra:
            letras_adivinadas.append(letra)
            print("¡Correcto!")
        else:
            intentos -= 1
            letras_falladas.append(letra)
            print("Incorrecto. Te quedan", intentos, "intentos.")
        if all(letra in letras_adivinadas for letra in palabra):
            print("¡Felicidades! Has adivinado la palabra:", palabra)
            break
    else:
        print("¡Has perdido! La palabra era:", palabra)


juego();